# ---------------------------------------------------------------------------
# Per-record-type document builders
# ---------------------------------------------------------------------------
#
# Each builder turns a *Create schema instance into a MongoDB document.
# They differ only in the default for optional fields, so a couple of lambdas
# and small functions keep them readable without hiding too much in magic.


def _str_or_default(default: str = ""):
    """Return a function that maps ``data.field`` to ``field or default``."""

    def _get(data, field_name):
        return getattr(data, field_name) or default

    return _get


def _asthma(data, pet_id, username, event_dt):
    return {
        "pet_id": pet_id,
        "date_time": event_dt,
        "duration": data.duration or "",
        "reason": data.reason or "",
        "inhalation": data.inhalation,
        "comment": data.comment or "",
        "username": username,
    }


def _defecation(data, pet_id, username, event_dt):
    return {
        "pet_id": pet_id,
        "date_time": event_dt,
        "stool_type": data.stool_type or "",
        "color": data.color or "Коричневый",
        "food": data.food or "",
        "comment": data.comment or "",
        "username": username,
    }


def _litter(data, pet_id, username, event_dt):
    return {
        "pet_id": pet_id,
        "date_time": event_dt,
        "comment": data.comment or "",
        "username": username,
    }


def _weight(data, pet_id, username, event_dt):
    return {
        "pet_id": pet_id,
        "date_time": event_dt,
        "weight": data.weight,
        "food": data.food or "",
        "comment": data.comment or "",
        "username": username,
    }


def _feeding(data, pet_id, username, event_dt):
    return {
        "pet_id": pet_id,
        "date_time": event_dt,
        "food_weight": (
            data.food_weight if data.food_weight is not None else None
        ),
        "comment": data.comment or "",
        "username": username,
    }


def _simple_with_type(type_field: str):
    """Builder for records that have just one extra ``str`` field beyond the base."""

    def _build(data, pet_id, username, event_dt):
        return {
            "pet_id": pet_id,
            "date_time": event_dt,
            type_field: getattr(data, type_field) or "",
            "comment": data.comment or "",
            "username": username,
        }

    return _build


